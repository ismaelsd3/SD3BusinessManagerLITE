    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
       int linha = tblOS.getSelectedRow();
        if (linha == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma Ordem de Serviço na tabela para excluir!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = Integer.parseInt(tableModelOS.getValueAt(linha, 0).toString());
        int confirmacao = javax.swing.JOptionPane.showConfirmDialog(this, "Deseja realmente excluir esta O.S.?", "Confirmar Exclusão", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
            if (osDAO.excluir(id)) {
                carregarTabelaOS();
                javax.swing.JOptionPane.showMessageDialog(this, "Ordem de Serviço excluída do banco!", "SD3 Manager", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linha = tblOS.getSelectedRow();
        if (linha == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma Ordem de Serviço na tabela para editar!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = Integer.parseInt(tableModelOS.getValueAt(linha, 0).toString());
        String servicoAtual = tableModelOS.getValueAt(linha, 2).toString();
        String valorAtual = tableModelOS.getValueAt(linha, 3).toString().replace("R$ ", "").trim();
        String statusAtual = tableModelOS.getValueAt(linha, 4).toString();

        String novoServico = javax.swing.JOptionPane.showInputDialog(this, "Descrição do Serviço:", servicoAtual);
        if (novoServico == null || novoServico.trim().isEmpty()) return;

        String novoValorStr = javax.swing.JOptionPane.showInputDialog(this, "Valor (R$):", valorAtual);
        if (novoValorStr == null || novoValorStr.trim().isEmpty()) return;

        double novoValor;
        try {
            novoValor = Double.parseDouble(novoValorStr.trim().replace(",", "."));
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Valor numérico inválido!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String[] opcoesStatus = {"Aberta", "Em Andamento", "Concluída"};
        String novoStatus = (String) javax.swing.JOptionPane.showInputDialog(
                this, "Status da O.S.:", "Editar Status",
                javax.swing.JOptionPane.QUESTION_MESSAGE, null, opcoesStatus, statusAtual
        );
        if (novoStatus == null) return;

        com.sd3.model.OrdensServico osAtualizada = new com.sd3.model.OrdensServico();
        osAtualizada.setId(id);
        osAtualizada.setDescricaoServico(novoServico.trim());
        osAtualizada.setValor(novoValor);
        osAtualizada.setStatus(novoStatus);

        if (osDAO.atualizar(osAtualizada)) {
            carregarTabelaOS();
            javax.swing.JOptionPane.showMessageDialog(this, "Ordem de Serviço atualizada no banco!", "SD3 Manager", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnEditarActionPerformed

