    private void btnSalvarOSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarOSActionPerformed
        int indexCliente = cbCliente.getSelectedIndex();
        if (indexCliente == -1 || cbStatus.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione o cliente e o status!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String servico = txtServico.getText().trim();
        String valorTexto = txtValor.getText().trim().replace(",", ".");
        String status = cbStatus.getSelectedItem().toString();

        if (servico.isEmpty() || valorTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha a descrição do serviço e o valor!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        double valor;
        try {
            valor = Double.parseDouble(valorTexto);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite um valor numérico válido (ex: 150.00)!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        com.sd3.model.Cliente clienteSelecionado = listaClientesCombo.get(indexCliente);
        com.sd3.model.OrdensServico novaOS = new com.sd3.model.OrdensServico();
        novaOS.setClienteId(clienteSelecionado.getId());
        novaOS.setDescricaoServico(servico);
        novaOS.setValor(valor);
        novaOS.setStatus(status);

        if (osDAO.inserir(novaOS)) {
            carregarTabelaOS();
            txtServico.setText("");
            txtValor.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, "Ordem de Serviço salva no banco com sucesso!", "SD3 Manager", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar Ordem de Serviço no banco.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarOSActionPerformed

