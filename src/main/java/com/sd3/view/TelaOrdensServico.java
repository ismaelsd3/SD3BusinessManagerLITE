    private void carregarDadosBanco() {
        // 1. Preenche o ComboBox de Clientes direto do MySQL
        cbCliente.removeAllItems();
        listaClientesCombo = clienteDAO.listarTodos();
        for (com.sd3.model.Cliente cli : listaClientesCombo) {
            cbCliente.addItem(cli.getNome());
        }

        // 2. Preenche o ComboBox de Status
        cbStatus.removeAllItems();
        cbStatus.addItem("Aberta");
        cbStatus.addItem("Em Andamento");
        cbStatus.addItem("Concluída");

        // 3. Carrega a tabela de O.S. do MySQL
        carregarTabelaOS();
    }

    private void carregarTabelaOS() {
        tableModelOS.setNumRows(0);
        java.util.List<com.sd3.model.OrdensServico> lista = osDAO.listarTodas();
        for (com.sd3.model.OrdensServico os : lista) {
            String valorFormatado = String.format(java.util.Locale.US, "R$ %.2f", os.getValor());
            tableModelOS.addRow(new Object[]{os.getId(), os.getNomeCliente(), os.getDescricaoServico(), valorFormatado, os.getStatus()});
        }
    }
    
    

